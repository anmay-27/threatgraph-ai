import { test, expect } from "@playwright/test";
import AxeBuilder from "@axe-core/playwright";
test.use({ reducedMotion: "reduce" });

test("studio search, sidebar and image composer work", async ({ page }) => {
  await page.goto("/analyze");
  await page.evaluate(() => localStorage.setItem("threatgraph-theme", "light"));
  await page.reload();
  await page.getByRole("button", { name: "Switch to dark mode" }).click();
  await expect(page.locator("html")).toHaveAttribute("data-theme", "dark");
  await page.reload();
  await expect(page.locator("html")).toHaveAttribute("data-theme", "dark");
  await expect(page.getByRole("heading", { name: /Analyze digital content/ })).toBeVisible();
  expect((await new AxeBuilder({ page }).withTags(["wcag2a", "wcag2aa", "wcag21a", "wcag21aa"]).analyze()).violations).toEqual([]);
  await page.screenshot({ path: "../docs/screenshots/studio-dark.png", fullPage: true });
  await page.getByRole("button", { name: "Switch to light mode" }).click();
  await expect(page.getByRole("heading", { name: /Analyze digital content/ })).toBeVisible();
  await page.keyboard.press("Control+k");
  const dialog = page.getByRole("dialog", { name: "Search workspace" });
  await expect(dialog).toBeVisible();
  await dialog.getByRole("textbox").fill("dashboard");
  await dialog.getByRole("button", { name: "Explore your dashboard" }).click();
  await expect(page).toHaveURL(/dashboard/);
  await page.goto("/analyze");
  await page.getByRole("button", { name: "Collapse sidebar" }).click();
  await expect(page.locator(".shell")).toHaveClass(/sidebar-collapsed/);
  await page.getByRole("button", { name: "Expand sidebar" }).click();
  await page.screenshot({ path: "../docs/screenshots/studio-desktop.png", fullPage: true });
  const chooser = page.waitForEvent("filechooser");
  await page.getByRole("button", { name: "Is this image AI?" }).click();
  await (await chooser).setFiles("../datasets/demo/illustration.png");
  await expect(page.getByAltText("Selected image preview")).toBeVisible();
  await page.getByRole("button", { name: "Remove selected file" }).click();
  await expect(page.getByAltText("Selected image preview")).toHaveCount(0);
  await expect(page.getByRole("button", { name: "Analyze Threat" })).toBeDisabled();
  await page.setViewportSize({ width: 390, height: 844 });
  await page.reload();
  await expect(page.locator(".shell")).toHaveClass(/sidebar-collapsed/);
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await page.screenshot({ path: "../docs/screenshots/studio-mobile.png", fullPage: true });
  await page.getByRole("button", { name: "Expand sidebar" }).click();
  await page.getByRole("link", { name: "Analysis history" }).click();
  await expect(page).toHaveURL(/history/);
  await expect(page.locator(".shell")).toHaveClass(/sidebar-collapsed/);
});
